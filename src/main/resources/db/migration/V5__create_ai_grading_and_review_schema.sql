  CONSTRAINT `fk_teacher_reviews_finalized_by` FOREIGN KEY (`finalized_by`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_teacher_reviews_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_teacher_reviews_submission_attempt_id` FOREIGN KEY (`submission_attempt_id`) REFERENCES `submission_attempts` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

